  MX_TIM2_Init();
  MX_TIM3_Init();
  MX_TIM4_Init();
  MX_TIM5_Init();
  /* USER CODE BEGIN 2 */
  HAL_Delay(1000);

  bno085_init(&hi2c3, BNO_RST_GPIO_Port, BNO_RST_Pin, BNO_INT_GPIO_Port, BNO_INT_Pin);
  bno085_hw_reset();

  uint8_t maj, min;
  int len;
  if (bno085_probe(&maj, &min)) {
      len = snprintf(txbuf, sizeof(txbuf), "BNO085 alive, SH-2 fw v%u.%u\r\n", maj, min);
  } else {
      len = snprintf(txbuf, sizeof(txbuf), "BNO085 not responding\r\n");
  }
  CDC_Transmit_FS((uint8_t*)txbuf, len);
  bno085_enable_rotation_vector(10000);

  encoder_init(&htim2, &htim3, &htim5);
  motor_init(&htim4);
  motor_stop_all();   /* explicit -- don't rely on power-on PWM register state */

  s_last_tick_50ms = HAL_GetTick();
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    if (bno085_service(&rv)) {
        int qlen = snprintf(txbuf, sizeof(txbuf), "Q,%.4f,%.4f,%.4f,%.4f\r\n",
                             rv.i, rv.j, rv.k, rv.real);
        CDC_Transmit_FS((uint8_t*)txbuf, qlen);
    }

    /* Encoder diagnostic stream, rate-limited to 20 Hz -- unlike the BNO085
     * path this isn't gated by an interrupt, so an explicit tick check is
     * the only thing stopping it from flooding CDC every main-loop pass. */
    if (HAL_GetTick() - s_last_tick_50ms >= 50) {
        s_last_tick_50ms = HAL_GetTick();
        encoder_update();
        int elen = snprintf(txbuf, sizeof(txbuf), "E,%ld,%ld,%ld\r\n",
                             (long)encoder_get_count(0),
                             (long)encoder_get_count(1),
                             (long)encoder_get_count(2));
        CDC_Transmit_FS((uint8_t*)txbuf, elen);
    }

    /* Your control law goes here: read encoder_get_delta()/get_count() and/or
     * rv, call motor_set(id, speed) per motor. Left undefined intentionally
     * -- this is bring-up/interfacing scope, not a control system. */

    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
  }
